# 구분자 +는 문자열일때는 연결하여 출력(띄어쓰기가 안된다)
print(1 + 3)
print('AI'+"강의실")

# print(1 + '이수현') int 와 string 타입이 다르기 때문에 출력에 오류가 생긴다.
# + 기호로 출력시에는 반드시 타입이 맞아야 한다.

print( str(1) + '이수현' )
